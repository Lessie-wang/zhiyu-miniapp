Page({
  data: {
    emotion: null,
    intensityColors: [],
    theoryInterpretation: '',
    storyTitle: '',
    storyContent: ''
  },

  onLoad: function(options) {
    if (options.emotion) {
      try {
        const emotion = JSON.parse(decodeURIComponent(options.emotion));

        // 生成强度颜色
        const intensityColors = emotion.subEmotions.map((subEmotion, idx) => {
          return this.hexToRgba(emotion.color, (idx + 1) * 0.15 + 0.1);
        });

        // 获取解读内容
        const interpretation = emotionInterpretations[emotion.name] || {
          theory: '这是一种重要的情绪体验，值得我们深入了解和探索。',
          storyTitle: '情绪的故事',
          story: '每一种情绪都有其独特的意义和价值，它们共同构成了我们丰富的内心世界。'
        };

        this.setData({
          emotion: emotion,
          intensityColors: intensityColors,
          theoryInterpretation: interpretation.theory,
          storyTitle: interpretation.storyTitle,
          storyContent: interpretation.story
        });
      } catch (e) {
        console.error('解析情绪数据失败:', e);
        wx.showToast({
          title: '加载失败',
          icon: 'none'
        });
      }
    }
  },

  hexToRgba: function(hex, opacity) {
    const r = parseInt(hex.slice(1, 3), 16);
    const g = parseInt(hex.slice(3, 5), 16);
    const b = parseInt(hex.slice(5, 7), 16);
    return `rgba(${r}, ${g}, ${b}, ${opacity})`;
  }
});
